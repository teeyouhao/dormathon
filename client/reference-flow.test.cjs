const assert = require('node:assert/strict')
const fs = require('node:fs/promises')
const path = require('node:path')
const { chromium } = require('playwright')

async function main() {
  const browser = await chromium.launch({ channel: 'msedge', headless: true })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  // Keep test projects out of the user's backend while exercising the real client save/restore path.
  const projects = new Map()
  await page.route('**/api/editor/projects**', async route => {
    const req = route.request()
    if (req.method() === 'POST') {
      const data = req.postDataJSON()
      data.id ||= 'test-project'
      projects.set(data.id, data)
      await route.fulfill({ json: { data } })
    } else await route.fulfill({ json: { data: [...projects.values()] } })
  })
  const media = path.join(__dirname, 'public/reference-DOOmrjGjWB4.mp4')
  const out = path.resolve(__dirname, '../../outputs')
  try {
    await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
    const card = page.locator('.reel-card').first()
    assert.match(await card.innerText(), /On the go delivery/)
    assert.equal(await page.getByText(/FEATURED TEMPLATE|Remake Studio/).count(), 0)
    const classes = await page.locator('.reel-card').evaluateAll(cards => cards.slice(0, 2).map(card => card.className))
    assert.equal(classes[0], classes[1], 'Reference uses same normal card classes')
    await card.locator('video').click({ position: { x: 100, y: 160 } })
    await page.waitForFunction(() => { const video = document.querySelector('.reel-card video'); return video.currentTime > 0.2 && !video.paused })
    assert.equal(await page.getByText('Video Details', { exact: true }).count(), 0)
    await card.getByText('On the go delivery', { exact: true }).click()
    await page.getByText('Video Details', { exact: true }).waitFor()
    assert.equal(await card.locator('video').evaluate(video => video.paused), true)
    await page.getByText('On the go delivery. Song by: Lastra', { exact: true }).waitFor()
    await page.getByRole('button', { name: 'Open in AI Editor' }).click()
    const editor = page.getByRole('dialog', { name: 'AI video editor', exact: true })
    await editor.waitFor()
    assert.equal(await editor.getByRole('button', { name: /^Original Part/ }).count(), 3)
    assert.equal(await editor.getByRole('button', { name: /^Uploads Part/ }).count(), 3)
    const original = await editor.getByRole('button', { name: /^Original Part 1/ }).boundingBox()
    const upload = await editor.getByRole('button', { name: /^Uploads Part 1/ }).boundingBox()
    assert(original.y < upload.y, 'Original track precedes Uploads')
    assert(await editor.getByRole('button', { name: 'Intro included', exact: true }).isDisabled())
    assert(await editor.getByRole('button', { name: 'Preview all 3 parts', exact: true }).isDisabled())
    await editor.getByRole('button', { name: 'Export', exact: true }).click()
    const modal = page.getByRole('dialog', { name: 'Export reel', exact: true })
    assert(await modal.getByRole('button', { name: 'Prepare export plan' }).isDisabled())
    await modal.getByRole('button', { name: 'Cancel' }).click()
    await editor.getByRole('button', { name: /^Original Part 2/ }).click()
    await page.locator('video[aria-label="Selected clip preview"]').evaluate(video => video.play()).catch(() => {})
    await page.waitForFunction(() => { const v = document.querySelector('video[aria-label="Selected clip preview"]'); return v?.currentTime > 2.2 && !v.paused })
    await page.waitForFunction(() => { const v = document.querySelector('video[aria-label="Selected clip preview"]'); return v?.paused && v.currentTime >= 3.95 }, { timeout: 8000 })
    assert.match(await editor.innerText(), /silver helmet/)
    const picker = editor.getByLabel('Upload selected part video')
    await editor.getByRole('button', { name: 'Upload Part 2', exact: true }).first().click({ trial: true })
    // A real chooser records the part before the file is selected.
    let chooser = page.waitForEvent('filechooser')
    await editor.getByRole('button', { name: 'Upload Part 2', exact: true }).first().click()
    await (await chooser).setFiles({ name: 'bad.txt', mimeType: 'text/plain', buffer: Buffer.from('not video') })
    await editor.getByRole('alert').filter({ hasText: 'Choose a video' }).waitFor()
    chooser = page.waitForEvent('filechooser')
    await editor.getByRole('button', { name: 'Upload Part 2', exact: true }).first().click()
    await (await chooser).setFiles(media)
    await editor.getByRole('button', { name: 'Uploads Part 2 ready', exact: true }).waitFor()
    assert.equal(await editor.getByRole('button', { name: 'Uploads Part 3 empty', exact: true }).count(), 1)
    await editor.getByRole('slider', { name: 'Part 2 clip start' }).fill('1')
    await editor.getByRole('button', { name: /^Original Part 3/ }).click()
    chooser = page.waitForEvent('filechooser')
    await editor.getByRole('button', { name: 'Upload Part 3', exact: true }).first().click()
    await (await chooser).setFiles(media)
    await editor.getByRole('button', { name: 'Uploads Part 3 ready', exact: true }).waitFor()
    await editor.getByRole('slider', { name: 'Part 3 clip start' }).fill('4')
    await editor.getByRole('button', { name: 'Undo', exact: true }).click()
    assert.equal(await editor.getByRole('button', { name: 'Uploads Part 3 empty', exact: true }).count(), 1)
    await editor.getByRole('button', { name: 'Redo', exact: true }).click()
    assert.equal(await editor.getByRole('button', { name: 'Uploads Part 3 ready', exact: true }).count(), 1)
    await editor.getByRole('button', { name: 'Text', exact: true }).click()
    await editor.locator('input[value="Your text here"]').fill('Fresh food')
    await editor.getByRole('button', { name: 'Filters', exact: true }).click()
    await editor.getByRole('button', { name: 'Vivid', exact: true }).click()
    await editor.getByRole('button', { name: 'Audio', exact: true }).click()
    await editor.getByText('Chill Vibes', { exact: true }).click()
    await editor.getByRole('button', { name: 'Sticker', exact: true }).click()
    await editor.getByText('Stickers', { exact: true }).waitFor()
    await editor.getByRole('button', { name: 'Effects', exact: true }).click()
    await editor.getByRole('button', { name: 'Zoom In', exact: true }).click()
    await editor.getByRole('button', { name: 'AI Concept', exact: true }).click()
    await editor.getByRole('button', { name: 'Remix', exact: true }).click()
    await editor.getByText('Upload Your Footage', { exact: true }).waitFor()
    await editor.getByRole('button', { name: 'Edit', exact: true }).click()
    await editor.getByRole('button', { name: 'Guidance', exact: true }).click()
    await editor.getByRole('button', { name: 'Preview all 3 parts', exact: true }).click()
    await page.waitForFunction(() => { const v = document.querySelector('video[aria-label="Selected clip preview"]'); return v?.currentTime > 0.3 && v.currentTime < 2 })
    await page.locator('video[aria-label="Selected clip preview"]').evaluate(video => { video.currentTime = 0.5; video.play().catch(() => {}) }).catch(() => {})
    await editor.getByRole('button', { name: 'Restart sequence', exact: true }).click()
    await page.waitForFunction(() => { const v = document.querySelector('video[aria-label="Selected clip preview"]'); return v?.currentTime < 0.3 })
    await page.waitForFunction(() => document.querySelector('[aria-label="AI video editor"]').textContent.includes('Preview all 3 parts') && document.querySelector('video[aria-label="Selected clip preview"]')?.paused, { timeout: 15000 })
    await editor.getByRole('button', { name: 'Apply Edits', exact: true }).click()
    await editor.getByText(/Preview settings applied/).waitFor()
    await editor.getByRole('button', { name: 'Save', exact: true }).click()
    await editor.getByText('Saved to Projects. Footage stays in this browser.', { exact: true }).waitFor()
    assert.equal(projects.size, 1)
    let project = [...projects.values()][0]
    assert.equal(project.edits.uploadedAssets.length, 2)
    assert.equal(project.edits.textOverlays[0].content, 'Fresh food')
    assert.equal(project.edits.selectedFilter, 'vivid')
    assert.equal(project.edits.selectedMusic, 'trending2')
    assert.equal(project.edits.selectedEffect, 'Zoom In')
    assert(!JSON.stringify(project.edits.uploadedAssets).includes('blob:'), 'Runtime URLs excluded from metadata')
    await editor.screenshot({ path: path.join(out, 'original-editor-three-parts.png') })
    await editor.getByRole('button', { name: 'Export', exact: true }).click()
    await modal.getByRole('button', { name: 'Prepare export plan' }).click()
    await modal.getByRole('button', { name: 'Download assembly plan (.json)' }).waitFor()
    const downloadPromise = page.waitForEvent('download')
    await modal.getByRole('button', { name: 'Download assembly plan (.json)' }).click()
    const download = await downloadPromise
    const plan = JSON.parse(await fs.readFile(await download.path(), 'utf8'))
    assert.equal(plan.status, 'assembly-plan-only')
    assert.deepEqual(plan.parts.map(part => part.outputRange), [[0, 2], [2, 4], [4, 8]])
    assert.deepEqual(plan.parts.map(part => part.trimStartSeconds), [0, 1, 4])
    await modal.getByRole('button', { name: 'Done', exact: true }).click()
    await editor.getByRole('button', { name: 'Back', exact: true }).click()
    await page.getByRole('button', { name: 'Projects', exact: true }).click()
    await page.getByRole('button', { name: 'Continue Editing' }).click()
    await editor.getByRole('button', { name: 'Uploads Part 3 ready', exact: true }).waitFor()
    assert.equal(await editor.getByRole('button', { name: 'Uploads Part 2 ready', exact: true }).count(), 1)
    assert(await editor.getByRole('button', { name: /^Original Part 1/ }).count() === 1)
    await editor.getByRole('button', { name: 'Back', exact: true }).click()
    await page.getByRole('button', { name: 'Trending Feed', exact: true }).click()
    await page.locator('.reel-card').nth(1).getByRole('button', { name: 'Use in Editor' }).click()
    assert.equal(await editor.getByRole('button', { name: 'Upload clip', exact: true }).count(), 1)
    assert.equal(await editor.getByLabel('Part 1 upload').count(), 0)
    assert.equal(errors.length, 0, errors.join('\n'))
    console.log('PASS: normal pinned card, native playback, details, original editor, 3 parts, locked intro, independent uploads, validation, trim, undo/redo, text/audio/filter/effects/modes, sequence/restart, save/restore, JSON export, ordinary reel unchanged, no runtime errors.')
  } finally { await browser.close() }
}
main().catch(error => { console.error(error); process.exitCode = 1 })
