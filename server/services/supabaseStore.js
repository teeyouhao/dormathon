import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const dataDir = path.join(__dirname, '..', 'data-store')
const localReelsFile = path.join(dataDir, 'reels.json')

function ensureDataDir() {
  if (!fs.existsSync(dataDir)) fs.mkdirSync(dataDir, { recursive: true })
  if (!fs.existsSync(localReelsFile)) fs.writeFileSync(localReelsFile, '[]')
}

function readLocalReels() {
  ensureDataDir()
  try { return JSON.parse(fs.readFileSync(localReelsFile, 'utf-8')) } catch { return [] }
}

function writeLocalReels(reels) {
  ensureDataDir()
  fs.writeFileSync(localReelsFile, JSON.stringify(reels, null, 2))
}

function getSupabaseConfig() {
  const url = process.env.SUPABASE_URL || process.env.SUPABASE_PROJECT_URL || ''
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.SUPABASE_SECRET_KEY || process.env.SUPABASE_ANON_KEY || ''
  const table = process.env.SUPABASE_REELS_TABLE || 'reels'
  return { url: url.replace(/\/$/, ''), key, table, configured: Boolean(url && key) }
}

function toIsoDate(value) {
  if (!value) return null
  const d = new Date(value)
  if (Number.isNaN(d.getTime())) return null
  return d.toISOString()
}

export function normalizeReel(reel, context = {}) {
  const platform = reel.platform || context.platform || 'unknown'
  const rawId = String(reel.id || reel.url || `${platform}-${Date.now()}-${Math.random()}`)
  const externalId = rawId.replace(new RegExp(`^${platform}[-_:]`, 'i'), '')

  return {
    external_id: externalId,
    platform,
    title: reel.title || 'Untitled reel',
    creator: reel.creator || '',
    creator_url: reel.creatorUrl || reel.creator_url || '',
    thumbnail: reel.thumbnail || '',
    views: Number(reel.views || 0),
    likes: Number(reel.likes || 0),
    shares: Number(reel.shares || 0),
    comments: Number(reel.comments || 0),
    duration: reel.duration || '',
    region: reel.region || context.region || 'all',
    location: reel.location || '',
    category: reel.category || reel.industry || context.industry || 'general',
    industry: reel.industry || reel.category || context.industry || 'general',
    url: reel.url || '',
    trending_rank: Number(reel.trendingRank || reel.trending_rank || 999),
    uploaded_at: toIsoDate(reel.uploadedAt || reel.uploaded_at),
    description: reel.description || '',
    tags: Array.isArray(reel.tags) ? reel.tags : [],
    source: context.source || 'unknown',
    fetched_at: new Date().toISOString(),
    raw: reel
  }
}

export function getSupabaseStatus() {
  const config = getSupabaseConfig()
  return {
    configured: config.configured,
    table: config.table,
    urlPresent: Boolean(config.url),
    keyPresent: Boolean(config.key)
  }
}

export function getReelsTableSql() {
  return `create table if not exists public.reels (
  id bigint generated by default as identity primary key,
  external_id text not null,
  platform text not null,
  title text not null,
  creator text,
  creator_url text,
  thumbnail text,
  views bigint default 0,
  likes bigint default 0,
  shares bigint default 0,
  comments bigint default 0,
  duration text,
  region text,
  location text,
  category text,
  industry text,
  url text,
  trending_rank integer,
  uploaded_at timestamptz,
  description text,
  tags text[] default '{}',
  source text,
  fetched_at timestamptz default now(),
  raw jsonb,
  unique(platform, external_id)
);

create index if not exists reels_platform_idx on public.reels(platform);
create index if not exists reels_region_idx on public.reels(region);
create index if not exists reels_industry_idx on public.reels(industry);
create index if not exists reels_fetched_at_idx on public.reels(fetched_at desc);`
}

export async function saveReelsLocally(reels, context = {}) {
  const normalized = reels.map(reel => normalizeReel(reel, context))
  const existing = readLocalReels()
  const byKey = new Map(existing.map(item => [`${item.platform}:${item.external_id}`, item]))
  for (const item of normalized) byKey.set(`${item.platform}:${item.external_id}`, { ...byKey.get(`${item.platform}:${item.external_id}`), ...item })
  const merged = Array.from(byKey.values()).sort((a, b) => new Date(b.fetched_at) - new Date(a.fetched_at))
  writeLocalReels(merged)
  return { target: 'local-json', saved: normalized.length, total: merged.length }
}

export async function upsertReels(reels, context = {}) {
  const normalized = reels.map(reel => normalizeReel(reel, context))
  const config = getSupabaseConfig()

  if (!normalized.length) {
    return { target: config.configured ? 'supabase' : 'local-json', saved: 0, configured: config.configured }
  }

  if (!config.configured) {
    const local = await saveReelsLocally(reels, context)
    return {
      ...local,
      configured: false,
      warning: 'Supabase URL/key is missing. Reels were stored in server/data-store/reels.json until Supabase is configured.'
    }
  }

  try {
    const response = await fetch(`${config.url}/rest/v1/${config.table}?on_conflict=platform,external_id`, {
      method: 'POST',
      headers: {
        apikey: config.key,
        Authorization: `Bearer ${config.key}`,
        'Content-Type': 'application/json',
        Prefer: 'resolution=merge-duplicates,return=representation'
      },
      body: JSON.stringify(normalized)
    })

    if (!response.ok) {
      const detail = await response.text().catch(() => '')
      const local = await saveReelsLocally(reels, context)
      return {
        ...local,
        configured: true,
        target: 'local-json-fallback',
        warning: `Supabase upsert failed. Check that table "${config.table}" exists and has the expected schema.`,
        detail: detail.slice(0, 300),
        schemaSql: getReelsTableSql()
      }
    }

    const savedRows = await response.json().catch(() => [])
    return {
      target: 'supabase',
      table: config.table,
      saved: Array.isArray(savedRows) ? savedRows.length : normalized.length,
      configured: true
    }
  } catch (err) {
    const local = await saveReelsLocally(reels, context)
    return {
      ...local,
      configured: true,
      target: 'local-json-fallback',
      warning: 'Supabase request failed. Reels were saved locally as a fallback.',
      detail: err.message
    }
  }
}

export async function getStoredReels({ platform = 'all', region = 'all', industry = 'all', limit = 100 } = {}) {
  const config = getSupabaseConfig()
  if (config.configured) {
    try {
      const params = new URLSearchParams()
      params.set('select', '*')
      params.set('order', 'fetched_at.desc')
      params.set('limit', String(limit))
      if (platform !== 'all') params.set('platform', `eq.${platform}`)
      if (region !== 'all') params.set('region', `eq.${region}`)
      if (industry !== 'all') params.set('industry', `eq.${industry}`)
      const response = await fetch(`${config.url}/rest/v1/${config.table}?${params.toString()}`, {
        headers: { apikey: config.key, Authorization: `Bearer ${config.key}` }
      })
      if (response.ok) return { target: 'supabase', data: await response.json() }
    } catch {}
  }

  let data = readLocalReels()
  if (platform !== 'all') data = data.filter(item => item.platform === platform)
  if (region !== 'all') data = data.filter(item => item.region === region)
  if (industry !== 'all') data = data.filter(item => item.industry === industry || item.category === industry)
  return { target: 'local-json', data: data.slice(0, limit) }
}
